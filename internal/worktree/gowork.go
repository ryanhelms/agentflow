package worktree

import (
	"bufio"
	"context"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"slices"
	"strconv"
	"strings"
)

// GoWorkResult reports a generated go.work.
type GoWorkResult struct {
	Path     string            `json:"path"`
	Go       string            `json:"go,omitempty"`
	Use      []string          `json:"use"`
	Replaces map[string]string `json:"replaces,omitempty"`
}

// WriteGoWork writes go.work into the worktree at dir from the configured
// worktree.go_work and excludes go.work and go.work.sum from Git. It returns
// nil when the repository configures no go.work.
func WriteGoWork(ctx context.Context, dir string, s Settings, rec Record) (*GoWorkResult, error) {
	gw := s.GoWork
	if gw == nil || len(gw.Use) == 0 {
		return nil, nil
	}
	res := &GoWorkResult{Path: filepath.Join(dir, "go.work"), Replaces: map[string]string{}}
	for _, use := range gw.Use {
		use = filepath.ToSlash(filepath.Clean(use))
		if use != "." && !strings.HasPrefix(use, "../") {
			use = "./" + use
		}
		res.Use = append(res.Use, use)
		if v, err := goDirective(filepath.Join(dir, filepath.FromSlash(use), "go.mod")); err != nil {
			return nil, err
		} else if compareVersions(v, res.Go) > 0 {
			res.Go = v
		}
	}
	modules := make([]string, 0, len(gw.Siblings))
	for module := range gw.Siblings {
		modules = append(modules, module)
	}
	slices.Sort(modules)
	var b strings.Builder
	b.WriteString("// Generated by agentflow from worktree.go_work in .agentflow/config.yml.\n")
	b.WriteString("// Not committed. Regenerate with `agentflow worktree go-work`.\n\n")
	if res.Go != "" {
		fmt.Fprintf(&b, "go %s\n\n", res.Go)
	}
	b.WriteString("use (\n")
	for _, use := range res.Use {
		fmt.Fprintf(&b, "\t%s\n", use)
	}
	b.WriteString(")\n")
	if len(modules) > 0 {
		b.WriteString("\n")
	}
	for _, module := range modules {
		sib := gw.Siblings[module]
		if sib.Repo == "" {
			return nil, fmt.Errorf("worktree.go_work.siblings.%s: repo is required", module)
		}
		target := filepath.Join(s.SiblingDir(sib.Repo, rec), filepath.FromSlash(sib.Path))
		res.Replaces[module] = target
		fmt.Fprintf(&b, "replace %s => %s\n", module, quoteGoWorkPath(target))
	}
	if err := os.WriteFile(res.Path, []byte(b.String()), 0o644); err != nil {
		return nil, err
	}
	return res, Exclude(ctx, dir, "/go.work", "/go.work.sum")
}

// SiblingDir is the checkout of repo to use with the task in rec: its worktree
// for the same branch, else its worktree for the same issue, else its primary checkout.
func (s Settings) SiblingDir(repo string, rec Record) string {
	if rec.Branch != "" {
		if dir := s.Path(repo, rec.Branch); isDir(dir) {
			return dir
		}
	}
	if rec.Issue != "" {
		if dir := findIssueWorktree(filepath.Join(s.Root, repo), rec.Issue); dir != "" {
			return dir
		}
	}
	return s.Checkout(repo)
}

func findIssueWorktree(root, issue string) string {
	found := ""
	_ = filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
		if err != nil || !d.IsDir() {
			return nil
		}
		if found != "" {
			return filepath.SkipAll
		}
		if _, err := os.Lstat(filepath.Join(path, ".git")); err != nil {
			if rel, _ := filepath.Rel(root, path); strings.Count(rel, string(filepath.Separator)) >= 3 {
				return filepath.SkipDir // branch names nest a few levels at most
			}
			return nil
		}
		if r, err := ReadRecord(path); err == nil && r.Issue == issue {
			found = path
		}
		return filepath.SkipDir // never walk into a checkout
	})
	return found
}

func isDir(path string) bool {
	info, err := os.Stat(path)
	return err == nil && info.IsDir()
}

func quoteGoWorkPath(p string) string {
	if strings.ContainsAny(p, " \t\"'`") {
		return strconv.Quote(p)
	}
	return p
}

// goDirective returns the `go` version in a go.mod.
func goDirective(path string) (string, error) {
	f, err := os.Open(path)
	if errors.Is(err, os.ErrNotExist) {
		return "", fmt.Errorf("worktree.go_work.use: no go.mod at %s", path)
	}
	if err != nil {
		return "", err
	}
	defer f.Close()
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		fields := strings.Fields(sc.Text())
		if len(fields) == 2 && fields[0] == "go" {
			return fields[1], nil
		}
	}
	return "", sc.Err()
}

// compareVersions compares Go versions such as 1.22, 1.22.3 and 1.23rc1.
func compareVersions(a, b string) int {
	pa, pb := versionParts(a), versionParts(b)
	for i := range max(len(pa), len(pb)) {
		var x, y int
		if i < len(pa) {
			x = pa[i]
		}
		if i < len(pb) {
			y = pb[i]
		}
		if x != y {
			if x < y {
				return -1
			}
			return 1
		}
	}
	return 0
}

func versionParts(v string) []int {
	if v == "" {
		return nil
	}
	var parts []int
	for _, field := range strings.Split(v, ".") {
		digits := field
		if i := strings.IndexFunc(digits, func(r rune) bool { return r < '0' || r > '9' }); i >= 0 {
			digits = digits[:i]
		}
		n, _ := strconv.Atoi(digits)
		parts = append(parts, n)
	}
	return parts
}
