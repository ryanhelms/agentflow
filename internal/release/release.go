// Package release implements semantic versioning for deployable units.
//
// Each repo lists its deployable units in .agentflow/releases.yml. Stable versions
// come from Conventional Commits on the default branch and are published as GitHub
// Releases by release-please (fully automatic). Other branches get prerelease
// versions that follow the repo's branching strategy, so staging builds are
// traceable to the release they lead to.
package release

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"

	"gopkg.in/yaml.v3"
)

// Build kinds a unit can produce.
const (
	Binary  = "binary"
	Image   = "image"
	Helm    = "helm"
	Library = "library"
)

// Strategies.
const (
	Trunk   = "trunk"   // short-lived branches into the default branch
	GitFlow = "gitflow" // develop, release/*, hotfix/*
)

// Unit is one independently versioned deployable.
type Unit struct {
	Name        string   `yaml:"name" json:"name"`
	Path        string   `yaml:"path" json:"path"`
	ReleaseType string   `yaml:"release_type" json:"release_type"` // release-please type: go, node, python, helm, terraform-module, simple
	Builds      []string `yaml:"builds" json:"builds"`
	Image       string   `yaml:"image,omitempty" json:"image,omitempty"` // e.g. ghcr.io/nscaledev/api
	Chart       string   `yaml:"chart,omitempty" json:"chart,omitempty"` // chart dir relative to path
	Dockerfile  string   `yaml:"dockerfile,omitempty" json:"dockerfile,omitempty"`
	Publish     string   `yaml:"publish,omitempty" json:"publish,omitempty"` // library registry: npm, pypi, go (tag only), terraform (tag only)
}

// Config is .agentflow/releases.yml.
type Config struct {
	Strategy      string `yaml:"strategy" json:"strategy"`
	DefaultBranch string `yaml:"default_branch,omitempty" json:"default_branch,omitempty"`
	Registry      string `yaml:"registry,omitempty" json:"registry,omitempty"` // default image/chart registry, e.g. ghcr.io/nscaledev
	Units         []Unit `yaml:"units" json:"units"`
}

// Monorepo reports whether the repo has more than one unit (tags carry the component).
func (c *Config) Monorepo() bool { return len(c.Units) > 1 }

// TagPrefix returns the tag prefix for a unit: "v" for single-unit repos, "<name>-v" otherwise.
func (c *Config) TagPrefix(u Unit) string {
	if c.Monorepo() {
		return u.Name + "-v"
	}
	return "v"
}

// Load reads .agentflow/releases.yml.
func Load(root string) (*Config, error) {
	b, err := os.ReadFile(filepath.Join(root, ".agentflow", "releases.yml"))
	if err != nil {
		return nil, err
	}
	var c Config
	if err := yaml.Unmarshal(b, &c); err != nil {
		return nil, fmt.Errorf(".agentflow/releases.yml: %w", err)
	}
	return &c, c.Validate()
}

var nameRe = regexp.MustCompile(`^[a-z0-9][a-z0-9-]*$`)

// Validate checks names, paths and build kinds.
func (c *Config) Validate() error {
	if c.Strategy != Trunk && c.Strategy != GitFlow {
		return fmt.Errorf("strategy must be %q or %q", Trunk, GitFlow)
	}
	if len(c.Units) == 0 {
		return errors.New("no units: list at least one deployable")
	}
	seen := map[string]bool{}
	for _, u := range c.Units {
		if !nameRe.MatchString(u.Name) {
			return fmt.Errorf("unit name %q: use lowercase letters, digits and dashes", u.Name)
		}
		if seen[u.Name] {
			return fmt.Errorf("duplicate unit %q", u.Name)
		}
		seen[u.Name] = true
		if u.Path == "" || strings.HasPrefix(u.Path, "/") || strings.Contains(u.Path, "..") {
			return fmt.Errorf("unit %s: path must be relative inside the repo", u.Name)
		}
		if u.ReleaseType == "" {
			return fmt.Errorf("unit %s: release_type is required", u.Name)
		}
		for _, b := range u.Builds {
			switch b {
			case Binary, Image, Helm, Library:
			default:
				return fmt.Errorf("unit %s: unknown build %q", u.Name, b)
			}
		}
	}
	return nil
}

// Save writes .agentflow/releases.yml with a header comment.
func (c *Config) Save(root string) error {
	b, err := yaml.Marshal(c)
	if err != nil {
		return err
	}
	header := "# Deployable units and how they are released. Generated by `agentflow release init`;\n" +
		"# edit freely, then run `agentflow release sync` to refresh the release-please files.\n"
	p := filepath.Join(root, ".agentflow", "releases.yml")
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		return err
	}
	return os.WriteFile(p, append([]byte(header), b...), 0o644)
}

// ---- detection ----

// Detect finds deployable units under root by looking for well-known files.
func Detect(root, owner string) []Unit {
	var units []Unit
	add := func(u Unit) {
		for i := range units {
			if units[i].Path == u.Path {
				units[i].Builds = mergeBuilds(units[i].Builds, u.Builds)
				if units[i].Chart == "" {
					units[i].Chart = u.Chart
				}
				if units[i].Image == "" {
					units[i].Image = u.Image
				}
				if units[i].Dockerfile == "" {
					units[i].Dockerfile = u.Dockerfile
				}
				if units[i].ReleaseType == "simple" && u.ReleaseType != "simple" && u.ReleaseType != "helm" {
					units[i].ReleaseType = u.ReleaseType
				}
				return
			}
		}
		units = append(units, u)
	}
	_ = filepath.WalkDir(root, func(p string, d os.DirEntry, err error) error {
		if err != nil {
			return nil
		}
		rel, _ := filepath.Rel(root, p)
		rel = filepath.ToSlash(rel)
		if d.IsDir() {
			base := d.Name()
			if rel != "." && (strings.HasPrefix(base, ".") || base == "node_modules" || base == "vendor" || base == "testdata" || base == "dist") {
				return filepath.SkipDir
			}
			return nil
		}
		dir := filepath.ToSlash(filepath.Dir(rel))
		unitDir := dir
		name := unitName(root, unitDir)
		switch d.Name() {
		case "Dockerfile":
			add(Unit{Name: name, Path: unitDir, ReleaseType: "simple", Builds: []string{Image}, Image: imageRef(owner, name), Dockerfile: "Dockerfile"})
		case "Chart.yaml":
			// Charts usually live in <unit>/chart or charts/<name>; attach to the parent unit when it has code.
			parent := filepath.ToSlash(filepath.Dir(dir))
			switch {
			case parent != "." && parent != "charts" && parent != "deploy" && hasCode(filepath.Join(root, parent)):
				add(Unit{Name: unitName(root, parent), Path: parent, ReleaseType: "simple", Builds: []string{Helm}, Chart: strings.TrimPrefix(dir, parent+"/")})
			case dir == "." && hasCode(root):
				add(Unit{Name: name, Path: ".", ReleaseType: "simple", Builds: []string{Helm}, Chart: "."})
			default:
				add(Unit{Name: unitName(root, dir), Path: dir, ReleaseType: "helm", Builds: []string{Helm}, Chart: "."})
			}
		case ".goreleaser.yaml", ".goreleaser.yml":
			add(Unit{Name: name, Path: unitDir, ReleaseType: "go", Builds: []string{Binary}})
		case "go.mod":
			if hasMain(filepath.Join(root, dir)) {
				add(Unit{Name: name, Path: unitDir, ReleaseType: "go", Builds: nil})
			} else {
				add(Unit{Name: name, Path: unitDir, ReleaseType: "go", Builds: []string{Library}, Publish: "go"})
			}
		case "package.json":
			if !strings.Contains(rel, "node_modules") {
				add(Unit{Name: name, Path: unitDir, ReleaseType: "node", Builds: []string{Library}, Publish: "npm"})
			}
		case "pyproject.toml":
			add(Unit{Name: name, Path: unitDir, ReleaseType: "python", Builds: []string{Library}, Publish: "pypi"})
		case "versions.tf":
			add(Unit{Name: name, Path: unitDir, ReleaseType: "terraform-module", Builds: []string{Library}, Publish: "terraform"})
		}
		return nil
	})
	// A Go main package with an image or binary is not a library.
	for i := range units {
		if containsStr(units[i].Builds, Image) || containsStr(units[i].Builds, Binary) {
			units[i].Builds = removeStr(units[i].Builds, Library)
			if units[i].Publish == "go" || units[i].Publish == "npm" || units[i].Publish == "pypi" {
				units[i].Publish = ""
			}
		}
		if len(units[i].Builds) == 0 {
			units[i].Builds = []string{Binary}
		}
		sort.Strings(units[i].Builds)
	}
	sort.Slice(units, func(a, b int) bool { return units[a].Path < units[b].Path })
	return units
}

func unitName(root, dir string) string {
	if dir == "." || dir == "" {
		return sanitize(filepath.Base(root))
	}
	return sanitize(filepath.Base(dir))
}

// RootUnit supplies a valid release unit for a project with no detected deployables.
func RootUnit(root string) Unit {
	return Unit{Name: unitName(root, "."), Path: ".", ReleaseType: "simple", Builds: []string{Binary}}
}

var nonName = regexp.MustCompile(`[^a-z0-9-]+`)

func sanitize(s string) string {
	s = strings.Trim(nonName.ReplaceAllString(strings.ToLower(s), "-"), "-")
	if s == "" {
		return "app"
	}
	return s
}

func imageRef(owner, name string) string {
	if owner == "" {
		return ""
	}
	return "ghcr.io/" + strings.ToLower(owner) + "/" + name
}

func hasCode(dir string) bool {
	for _, f := range []string{"go.mod", "package.json", "pyproject.toml", "Dockerfile", "Cargo.toml"} {
		if _, err := os.Stat(filepath.Join(dir, f)); err == nil {
			return true
		}
	}
	return false
}

var mainRe = regexp.MustCompile(`(?m)^package main\b`)

func hasMain(dir string) bool {
	found := false
	_ = filepath.WalkDir(dir, func(p string, d os.DirEntry, err error) error {
		if err != nil || found {
			return filepath.SkipAll
		}
		if d.IsDir() && (d.Name() == "vendor" || d.Name() == "testdata" || strings.HasPrefix(d.Name(), ".")) && p != dir {
			return filepath.SkipDir
		}
		if strings.HasSuffix(p, ".go") && !strings.HasSuffix(p, "_test.go") {
			//nolint:gosec // reads files inside the developer's own checkout during detection
			if b, err := os.ReadFile(p); err == nil && mainRe.Match(b) {
				found = true
			}
		}
		return nil
	})
	return found
}

func mergeBuilds(a, b []string) []string {
	for _, x := range b {
		if !containsStr(a, x) {
			a = append(a, x)
		}
	}
	return a
}

func containsStr(s []string, v string) bool {
	for _, x := range s {
		if x == v {
			return true
		}
	}
	return false
}

func removeStr(s []string, v string) []string {
	var out []string
	for _, x := range s {
		if x != v {
			out = append(out, x)
		}
	}
	return out
}

// ---- release-please files ----

// PleaseConfig builds release-please-config.json for the units.
func (c *Config) PleaseConfig() map[string]any {
	pkgs := map[string]any{}
	for _, u := range c.Units {
		p := map[string]any{
			"release-type":             u.ReleaseType,
			"component":                u.Name,
			"package-name":             u.Name,
			"include-component-in-tag": c.Monorepo(),
		}
		// Keep Chart.yaml in step with the release for units that ship a chart alongside
		// code (pure helm units are versioned by release-please's helm strategy).
		if containsStr(u.Builds, Helm) && u.Chart != "" && u.ReleaseType != "helm" {
			chart := filepath.ToSlash(filepath.Join(u.Chart, "Chart.yaml"))
			p["extra-files"] = []any{
				map[string]any{"type": "yaml", "path": chart, "jsonpath": "$.version"},
				map[string]any{"type": "yaml", "path": chart, "jsonpath": "$.appVersion"},
			}
		}
		pkgs[u.Path] = p
	}
	return map[string]any{
		"$schema":                        "https://raw.githubusercontent.com/googleapis/release-please/main/schemas/config.json",
		"include-v-in-tag":               true,
		"tag-separator":                  "-",
		"separate-pull-requests":         false,
		"bump-minor-pre-major":           true,
		"bump-patch-for-minor-pre-major": false,
		"changelog-sections": []any{
			map[string]any{"type": "feat", "section": "Features"},
			map[string]any{"type": "fix", "section": "Fixes"},
			map[string]any{"type": "perf", "section": "Performance"},
			map[string]any{"type": "revert", "section": "Reverts"},
			map[string]any{"type": "refactor", "section": "Refactoring", "hidden": true},
			map[string]any{"type": "docs", "section": "Docs", "hidden": true},
			map[string]any{"type": "chore", "section": "Chores", "hidden": true},
		},
		"packages": pkgs,
	}
}

// Manifest builds .release-please-manifest.json, keeping versions already released.
func (c *Config) Manifest(existing map[string]string) map[string]string {
	m := map[string]string{}
	for _, u := range c.Units {
		if v, ok := existing[u.Path]; ok && v != "" {
			m[u.Path] = v
		} else {
			m[u.Path] = "0.0.0"
		}
	}
	return m
}

// ---- versions ----

// Version is a semantic version.
type Version struct {
	Major, Minor, Patch int
}

func (v Version) String() string { return fmt.Sprintf("%d.%d.%d", v.Major, v.Minor, v.Patch) }

// ParseTagVersion parses "<prefix>1.2.3".
func ParseTagVersion(tag, prefix string) (Version, bool) {
	s, ok := strings.CutPrefix(tag, prefix)
	if !ok {
		return Version{}, false
	}
	parts := strings.Split(s, ".")
	if len(parts) != 3 {
		return Version{}, false
	}
	var n [3]int
	for i, p := range parts {
		v, err := strconv.Atoi(p)
		if err != nil {
			return Version{}, false
		}
		n[i] = v
	}
	return Version{n[0], n[1], n[2]}, true
}

// Bump kinds.
const (
	BumpNone  = "none"
	BumpPatch = "patch"
	BumpMinor = "minor"
	BumpMajor = "major"
)

var (
	breakingRe = regexp.MustCompile(`^[a-z]+(\([^)]*\))?!:`)
	featRe     = regexp.MustCompile(`^feat(\([^)]*\))?:`)
	fixRe      = regexp.MustCompile(`^(fix|perf)(\([^)]*\))?:`)
)

// BumpFor returns the bump implied by commit messages (release-please rules).
func BumpFor(messages []string) string {
	bump := BumpNone
	rank := map[string]int{BumpNone: 0, BumpPatch: 1, BumpMinor: 2, BumpMajor: 3}
	for _, m := range messages {
		subject := strings.SplitN(strings.TrimSpace(m), "\n", 2)[0]
		b := BumpNone
		switch {
		case breakingRe.MatchString(subject) || strings.Contains(m, "\nBREAKING CHANGE:") || strings.Contains(m, "\nBREAKING-CHANGE:"):
			b = BumpMajor
		case featRe.MatchString(subject):
			b = BumpMinor
		case fixRe.MatchString(subject):
			b = BumpPatch
		}
		if rank[b] > rank[bump] {
			bump = b
		}
	}
	return bump
}

// Next applies a bump. Before 1.0.0, breaking changes bump the minor version
// (bump-minor-pre-major), matching the release-please config agentflow generates.
func Next(cur Version, bump string) Version {
	switch bump {
	case BumpMajor:
		if cur.Major == 0 {
			return Version{0, cur.Minor + 1, 0}
		}
		return Version{cur.Major + 1, 0, 0}
	case BumpMinor:
		return Version{cur.Major, cur.Minor + 1, 0}
	case BumpPatch:
		return Version{cur.Major, cur.Minor, cur.Patch + 1}
	}
	return cur
}

// BranchKind classifies a branch under a strategy.
func BranchKind(strategy, branch, defaultBranch string) string {
	switch {
	case branch == defaultBranch:
		return "default"
	case strategy == GitFlow && branch == "develop":
		return "develop"
	case strings.HasPrefix(branch, "release/"):
		return "release"
	case strings.HasPrefix(branch, "hotfix/"):
		return "hotfix"
	}
	return "feature"
}

// Preid returns the prerelease identifier for a branch kind.
func Preid(kind string) string {
	switch kind {
	case "develop":
		return "alpha"
	case "release":
		return "rc"
	case "hotfix":
		return "hotfix"
	case "feature":
		return "pr"
	}
	return ""
}

var nonIdent = regexp.MustCompile(`[^0-9A-Za-z-]+`)

// Prerelease builds the version string for a build on a non-default branch:
// <next>-<preid>.<n>+<sha>, where n is the number of commits since the last tag.
// SemVer orders it before the release it leads to.
func Prerelease(next Version, kind string, n int, sha string) string {
	id := Preid(kind)
	if id == "" {
		return next.String()
	}
	s := fmt.Sprintf("%s-%s.%d", next, id, n)
	if sha = nonIdent.ReplaceAllString(sha, ""); sha != "" {
		s += "+" + sha
	}
	return s
}
